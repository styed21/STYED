"use client";

import { useEffect, useId, useMemo, useRef, useState } from "react";
import { motion, AnimatePresence, useInView } from "framer-motion";
import { useTheme } from "next-themes";
import { useReducedMotion } from "@/src/hooks/useMotion";
import { cn } from "@/src/lib/utils";
import region from "@/src/data/map-region.json";

export type MapLocation = { lat: number; lng: number; label?: string };
export interface MapProps {
  dots?: Array<{ start: MapLocation; end: MapLocation }>;
  locations?: MapLocation[];
  lineColor?: string;
  showLabels?: boolean;
  labelClassName?: string;
  animationDuration?: number;
  loop?: boolean;
  className?: string;
  ariaLabel?: string;
}
const noRoutes: NonNullable<MapProps["dots"]> = [];
const noLocations: MapLocation[] = [];
const validLocation = (p: MapLocation) =>
  Number.isFinite(p.lat) &&
  Number.isFinite(p.lng) &&
  p.lat >= region.lat.min &&
  p.lat <= region.lat.max &&
  p.lng >= region.lng.min &&
  p.lng <= region.lng.max;

const projectPoint = ({ lat, lng }: MapLocation) => ({
  x: ((lng - region.lng.min) / (region.lng.max - region.lng.min)) * 800,
  y: ((region.lat.max - lat) / (region.lat.max - region.lat.min)) * 400,
});
const curve = (start: MapLocation, end: MapLocation) => {
  const a = projectPoint(start),
    b = projectPoint(end);
  return `M ${a.x} ${a.y} Q ${(a.x + b.x) / 2} ${Math.max(12, Math.min(a.y, b.y) - 50)} ${b.x} ${b.y}`;
};

/** Adapted from the supplied component for Vite, with precomputed dotted-map SVGs.
 * A shared equirectangular projection keeps the map layer and pins aligned.
 * Assets are generated by scripts/generate-map.mjs; country geometry never enters the browser bundle.
 */
export function WorldMap({
  dots = noRoutes,
  locations = noLocations,
  lineColor = "#bf643c",
  showLabels = true,
  labelClassName = "text-xs",
  animationDuration = 2,
  loop = true,
  className,
  ariaLabel = "World map with highlighted locations",
}: MapProps) {
  const root = useRef<HTMLDivElement>(null);
  const svgRef = useRef<SVGSVGElement>(null);
  const id = useId().replace(/:/g, "");
  const { resolvedTheme } = useTheme();
  const reduced = useReducedMotion();
  const inView = useInView(root, { amount: 0.15 });
  const [visible, setVisible] = useState(true);

  const [hoveredLocation, setHoveredLocation] = useState<string | null>(null);
  const playing = inView && visible && !reduced;
  const routes = useMemo(
    () =>
      dots.filter((dot) => validLocation(dot.start) && validLocation(dot.end)),
    [dots],
  );
  useEffect(() => {
    const update = () => setVisible(!document.hidden);
    update();
    document.addEventListener("visibilitychange", update);
    return () => document.removeEventListener("visibilitychange", update);
  }, []);
  const points = useMemo(
    () => [
      ...new Map(
        [...locations, ...routes.flatMap((dot) => [dot.start, dot.end])]
          .filter(validLocation)
          .map((p) => [p.lat + "," + p.lng, p]),
      ).values(),
    ],
    [routes, locations],
  );
  const duration = Number.isFinite(animationDuration)
    ? Math.max(0.2, animationDuration)
    : 2;
  const total = Math.max(0, routes.length - 1) * 0.3 + duration;
  const cycle = total + 2;
  return (
    <div
      ref={root}
      className={cn(
        "world-map relative w-full overflow-hidden rounded-lg font-sans",
        className,
      )}
    >
      <img
        src={`./assets/world-dots-${resolvedTheme === "dark" ? "dark" : "light"}.svg`}
        alt=""
        aria-hidden="true"
        width="800"
        height="400"
        loading="lazy"
        draggable={false}
        className="world-map-image pointer-events-none h-full w-full select-none"
      />
      <svg
        ref={svgRef}
        viewBox="0 0 800 400"
        preserveAspectRatio="none"
        className="absolute inset-0 h-full w-full select-none"
        role="group"
        aria-label={ariaLabel}
      >
        <defs>
          <linearGradient id={id + "-path"}>
            <stop offset="0%" stopColor={lineColor} stopOpacity="0" />
            <stop offset="15%" stopColor={lineColor} />
            <stop offset="85%" stopColor={lineColor} />
            <stop offset="100%" stopColor={lineColor} stopOpacity="0" />
          </linearGradient>
          <filter id={id + "-glow"}>
            <feGaussianBlur stdDeviation="1.5" />
            <feMerge>
              <feMergeNode />
              <feMergeNode in="SourceGraphic" />
            </feMerge>
          </filter>
        </defs>
        {routes.map((dot, i) => (
          <g key={i}>
            <motion.path
              d={curve(dot.start, dot.end)}
              fill="none"
              stroke={`url(#${id}-path)`}
              strokeWidth="1.4"
              initial={false}
              animate={
                playing
                  ? { pathLength: loop ? [0, 0, 1, 1, 0] : [0, 1] }
                  : { pathLength: 1 }
              }
              transition={
                playing
                  ? loop
                    ? {
                        duration: cycle,
                        times: [
                          0,
                          (i * 0.3) / cycle,
                          (i * 0.3 + duration) / cycle,
                          (total + 1.5) / cycle,
                          1,
                        ],
                        ease: "easeInOut",
                        repeat: Infinity,
                      }
                    : { duration, delay: i * 0.3 }
                  : { duration: 0 }
              }
            />
            {playing && loop && (
              <motion.circle
                r="3"
                fill={lineColor}
                style={{ offsetPath: `path('${curve(dot.start, dot.end)}')` }}
                animate={{ offsetDistance: ["0%", "100%"], opacity: [0, 1, 0] }}
                transition={{
                  duration,
                  delay: i * 0.3,
                  repeat: Infinity,
                  repeatDelay: cycle - duration,
                  ease: "easeInOut",
                }}
              />
            )}
          </g>
        ))}
        {points.map((point, i) => {
          const p = projectPoint(point);
          const label = point.label || "Location " + (i + 1);
          return (
            <g
              key={point.lat + "," + point.lng}
              role="button"
              tabIndex={0}
              aria-label={label}
              onMouseEnter={() => setHoveredLocation(label)}
              onMouseLeave={() => setHoveredLocation(null)}
              onFocus={() => setHoveredLocation(label)}
              onBlur={() => setHoveredLocation(null)}
              onClick={() => setHoveredLocation(label)}
              onKeyDown={(event) => {
                if (event.key === "Enter" || event.key === " ") {
                  event.preventDefault();
                  setHoveredLocation(label);
                }
              }}
            >
              <circle cx={p.x} cy={p.y} r="17" fill="transparent" />
              <motion.circle
                cx={p.x}
                cy={p.y}
                fill={lineColor}
                initial={false}
                animate={
                  playing && loop
                    ? { r: [4, 17], opacity: [0.5, 0] }
                    : { r: 8, opacity: 0.15 }
                }
                transition={
                  playing && loop
                    ? { duration: 2.2, repeat: Infinity, ease: "easeOut" }
                    : { duration: 0 }
                }
              />
              <circle
                cx={p.x}
                cy={p.y}
                r="4"
                fill={lineColor}
                filter={`url(#${id}-glow)`}
              />
              <circle cx={p.x} cy={p.y} r="1.6" fill="#fff" />
            </g>
          );
        })}
      </svg>
      {showLabels &&
        points
          .filter((p) => p.label)
          .map((point) => {
            const p = projectPoint(point);
            return (
              <span
                key={point.lat + "," + point.lng}
                className={cn(
                  "map-location-label absolute rounded-md border px-3 py-2",
                  labelClassName,
                )}
                style={{ left: p.x / 8 + "%", top: p.y / 4 + "%" }}
              >
                {point.label}
              </span>
            );
          })}
      <AnimatePresence>
        {hoveredLocation && (
          <motion.div
            className="map-tooltip absolute bottom-4 left-4 rounded-md px-3 py-2 text-xs"
            initial={{ opacity: 0, y: 4 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: 4 }}
          >
            {hoveredLocation}
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
